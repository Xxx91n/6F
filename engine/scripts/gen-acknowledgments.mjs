// ---- 极简解析 upstream-lock.yaml（这文件的形状就这么点：'  - id: X' 加 '    status: s'） ----
function parseLock(text) {
  const entries = [];
  let cur = null;
  for (const line of text.split(/\r?\n/)) {
    const mId = line.match(/^\s{2}-\s+id:\s*(\S+)/);
    if (mId) { cur = { id: mId[1] }; entries.push(cur); continue; }
    const mSt = line.match(/^\s{4}status:\s*(\S+)/);
    if (mSt && cur) cur.status = mSt[1];
  }
  return entries;
}

let _active = null;
function activeIds() {
  if (_active) return _active;
  const entries = parseLock(fs.readFileSync(LOCK, 'utf8'));
  _active = entries.filter(e => e.status === 'active').map(e => e.id);
  return _active;
}

function renderBlock(lang) {
  const head = lang === 'zh' ? '## 致谢 {#acknowledgments}' : '## Acknowledgments {#acknowledgments}';
  const intro = lang === 'zh'
    ? '6F 建立在这些上游组件之上——就是 [engine/upstream-lock.yaml](engine/upstream-lock.yaml) 里状态为 active 的那组：'
    : '6F builds on these upstream components — the `active` set in [engine/upstream-lock.yaml](engine/upstream-lock.yaml):';
  const foot = lang === 'zh'
    ? '*完整上游记录（含 planned／evaluating／retired 行）见 [engine/upstream-lock.yaml](engine/upstream-lock.yaml)；法律上的署名义务由 NOTICE/许可证文件承担，本节只给人看致谢。*'
    : '*The full upstream record — including planned / evaluating / retired rows — lives in [engine/upstream-lock.yaml](engine/upstream-lock.yaml). Legal attribution obligations are carried by NOTICE/license files; this section is the human-readable credit list only.*';
  const lines = activeIds().map(id => {
    const tp = TEMPLATES[id];
    if (!tp) return '- **MISSING-TEMPLATE:' + id + '**'; // 防御网——能渲染那道门已经先拦住了
    return '- **[' + tp.name + '](' + tp.url + ')** — ' + tp[lang];
  });
  return [BANNER, head, '', intro, ''].concat(lines).concat(['', foot, MARK_END]).join('\n');
}

// 两头核：模板里的键跟 lock 的 active 集合互对，两边都算差集（模板缺了 active＝人没写 / 模板里有非 active＝走样了）
function setDrift() {
  const active = new Set(activeIds());
  const tkeys = new Set(Object.keys(TEMPLATES));
  const missing = [...active].filter(id => !tkeys.has(id));
  const extra = [...tkeys].filter(id => !active.has(id));
  return { missing, extra };
}

const BLOCK_RE = /<!--\s*acknowledgments:start[\s\S]*?<!--\s*acknowledgments:end\s*-->/;

function applyBlock(content, block, headingRe, earlyAnchorRe) {
  if (BLOCK_RE.test(content)) return content.replace(BLOCK_RE, block);
  const lines = content.split('\n');
  let idx = earlyAnchorRe ? lines.findIndex(l => earlyAnchorRe.test(l)) : -1;
  if (idx < 0) idx = lines.findIndex(l => headingRe.test(l));
  if (idx < 0) return null;
  lines.splice(idx, 0, block, '');
  return lines.join('\n');
}

const norm = s => s.replace(/\r\n/g, '\n');
const eolOf = s => (s.indexOf('\r\n') >= 0 ? '\r\n' : '\n');

function expectedEn() {
  const en = norm(fs.readFileSync(EN_PATH, 'utf8'));
  return applyBlock(en, renderBlock('en'), /^##\s+Honesty notes\s*$/, null);
}

function expectedZh(enAfter) {
  // 戳按盘上英文原文来算：sha256(英文原文, utf8)——期望值先换成目标那份的行尾形态再哈希（都用 LF 的话跟原文等价）
  const enDiskEol = eolOf(fs.readFileSync(EN_PATH, 'utf8'));
  const hash = crypto.createHash('sha256').update(enAfter.split('\n').join(enDiskEol), 'utf8').digest('hex').slice(0, 12);
  const zh = norm(fs.readFileSync(ZH_PATH, 'utf8'));
  let out = applyBlock(zh, renderBlock('zh'), /^##\s+.*\{#honesty-notes\}\s*$/, /<a\s+id="honesty-notes"><\/a>/);
  if (out === null) return null;
  out = out.replace(/<!--\s*sync:\s*[0-9a-f]{12}\s*-->/, '<!-- sync: ' + hash + ' -->');
  return out;
}

