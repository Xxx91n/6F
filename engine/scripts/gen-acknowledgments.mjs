// ---- upstream-lock.yaml 极简解析（本文件形制约：'  - id: X' + '    status: s'） ----
function parseLock(text) {
  const entries = [];
  let cur = null;
  for (const line of text.split(/\r?\n/)) {
    const mId = line.match(/^\s{2}-\s+id:\s*(\S+)/);
    if (mId) { cur = { id: mId[1] }; entries.push(cur); continue; }
    const mSt = line.match(/^\s{4}status:\s*(\S+)/);
    if (mSt && cur) cur.status = mSt[1];
  }
  return entries;
}

let _active = null;
function activeIds() {
  if (_active) return _active;
  const entries = parseLock(fs.readFileSync(LOCK, 'utf8'));
  _active = entries.filter(e => e.status === 'active').map(e => e.id);
  return _active;
}

function renderBlock(lang) {
  const head = lang === 'zh' ? '## 致谢 {#acknowledgments}' : '## Acknowledgments';
  const intro = lang === 'zh'
    ? '6F 站在这些上游组件之上——即 [engine/upstream-lock.yaml](engine/upstream-lock.yaml) 的 active 集：'
    : '6F stands on these upstream components — the active set of [engine/upstream-lock.yaml](engine/upstream-lock.yaml):';
  const foot = lang === 'zh'
    ? '*完整上游账目（含 planned／evaluating／retired 行）见 [engine/upstream-lock.yaml](engine/upstream-lock.yaml)；法律承接义务由 NOTICE/许可证文件承载，本节仅为人读致谢面。*'
    : '*The full upstream ledger — including planned / evaluating / retired rows — lives in [engine/upstream-lock.yaml](engine/upstream-lock.yaml). Legal attribution obligations are carried by NOTICE/license files; this section is the human credit surface only.*';
  const lines = activeIds().map(id => {
    const tp = TEMPLATES[id];
    if (!tp) return '- **MISSING-TEMPLATE:' + id + '**'; // 防御网——renderable 门已先行拦截
    return '- **[' + tp.name + '](' + tp.url + ')** — ' + tp[lang];
  });
  return [BANNER, head, '', intro, ''].concat(lines).concat(['', foot, MARK_END]).join('\n');
}

// closed 对账：模板键集 ⇔ lock active 集双向差集（模板缺 active=人没写 / 模板有非 active=漂移）
function setDrift() {
  const active = new Set(activeIds());
  const tkeys = new Set(Object.keys(TEMPLATES));
  const missing = [...active].filter(id => !tkeys.has(id));
  const extra = [...tkeys].filter(id => !active.has(id));
  return { missing, extra };
}

const BLOCK_RE = /<!--\s*acknowledgments:start[\s\S]*?<!--\s*acknowledgments:end\s*-->/;

function applyBlock(content, block, headingRe, earlyAnchorRe) {
  if (BLOCK_RE.test(content)) return content.replace(BLOCK_RE, block);
  const lines = content.split('\n');
  let idx = earlyAnchorRe ? lines.findIndex(l => earlyAnchorRe.test(l)) : -1;
  if (idx < 0) idx = lines.findIndex(l => headingRe.test(l));
  if (idx < 0) return null;
  lines.splice(idx, 0, block, '');
  return lines.join('\n');
}

const norm = s => s.replace(/\r\n/g, '\n');
const eolOf = s => (s.indexOf('\r\n') >= 0 ? '\r\n' : '\n');

function expectedEn() {
  const en = norm(fs.readFileSync(EN_PATH, 'utf8'));
  return applyBlock(en, renderBlock('en'), /^##\s+Honesty notes\s*$/, null);
}

function expectedZh(enAfter) {
  // 戳口径对齐 73-check C 组：sha256(盘上 EN 原文, utf8)——期望值换算成目标 EOL 形态再哈希（LF 锁下与原文等价）
  const enDiskEol = eolOf(fs.readFileSync(EN_PATH, 'utf8'));
  const hash = crypto.createHash('sha256').update(enAfter.split('\n').join(enDiskEol), 'utf8').digest('hex').slice(0, 12);
  const zh = norm(fs.readFileSync(ZH_PATH, 'utf8'));
  let out = applyBlock(zh, renderBlock('zh'), /^##\s+.*\{#honesty-notes\}\s*$/, /<a\s+id="honesty-notes"><\/a>/);
  if (out === null) return null;
  out = out.replace(/<!--\s*sync:\s*[0-9a-f]{12}\s*-->/, '<!-- sync: ' + hash + ' -->');
  return out;
}

const check = process.argv.indexOf('--check') >= 0;
const drift = setDrift();
const problems = [];
if (drift.missing.length) problems.push('template-missing(active 无模板): ' + drift.missing.join(','));
if (drift.extra.length) problems.push('template-extra(模板非 active): ' + drift.extra.join(','));
if (!activeIds().length) problems.push('lock-parse-empty: active 集为空（锁表解析失败？）');

// 模板集不完整时禁渲染——先报归因行再退（避免 tp.name 裸 TypeError 吞诊断；审计 F-01）
const renderable = drift.missing.length === 0 && activeIds().length > 0;
const expEn = renderable ? expectedEn() : null;
if (renderable && expEn === null) problems.push('en-anchor-missing: README.md 无 ## Honesty notes 插入位');
const expZh = expEn === null ? null : expectedZh(expEn);
if (renderable && expEn !== null && expZh === null) problems.push('zh-anchor-missing: README.zh-CN.md 无 honesty 锚/标题插入位');

for (const pair of [['README.md', EN_PATH, expEn], ['README.zh-CN.md', ZH_PATH, expZh]]) {
  const label = pair[0], path = pair[1], expected = pair[2];
  if (expected === null) continue;
  const cur = fs.readFileSync(path, 'utf8');
  const same = norm(cur) === expected;
  if (check) {
    console.log((same ? 'CLEAN ' : 'DRIFT ') + label);
    if (!same) problems.push(label + ' drift（regen 可修：node engine/scripts/gen-acknowledgments.mjs）');
  } else if (same) {
    console.log('CLEAN ' + label);
  } else {
    const had = BLOCK_RE.test(cur);
    fs.writeFileSync(path, expected.split('\n').join(eolOf(cur)), 'utf8');
    console.log((had ? 'DRIFT->WROTE ' : 'NEW->WROTE ') + label);
  }
}

if (problems.length) {
  console.log('PROBLEMS ' + problems.join(' | '));
  process.exit(1);
}
console.log(check ? 'CHECK-OK acknowledgments 锚段与锁表 active 集一致' : 'DONE acknowledgments 锚段已同步');
