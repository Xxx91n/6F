// 模板集不齐就别渲染——先把谁缺了报出来再退（免得 tp.name 直接抛个 TypeError 把诊断吞了；审计 F-01）
const renderable = drift.missing.length === 0 && activeIds().length > 0;
const expEn = renderable ? expectedEn() : null;
if (renderable && expEn === null) problems.push('en-anchor-missing: README.md 无 ## Honesty notes 插入位');
const expZh = expEn === null ? null : expectedZh(expEn);
if (renderable && expEn !== null && expZh === null) problems.push('zh-anchor-missing: README.zh-CN.md 无 honesty 锚/标题插入位');

for (const pair of [['README.md', EN_PATH, expEn], ['README.zh-CN.md', ZH_PATH, expZh]]) {
  const label = pair[0], path = pair[1], expected = pair[2];
  if (expected === null) continue;
  const cur = fs.readFileSync(path, 'utf8');
  const same = norm(cur) === expected;
  if (check) {
    console.log((same ? 'CLEAN ' : 'DRIFT ') + label);
    if (!same) problems.push(label + ' drift（regen 可修：node engine/scripts/gen-acknowledgments.mjs）');
  } else if (same) {
    console.log('CLEAN ' + label);
  } else {
    const had = BLOCK_RE.test(cur);
    fs.writeFileSync(path, expected.split('\n').join(eolOf(cur)), 'utf8');
    console.log((had ? 'DRIFT->WROTE ' : 'NEW->WROTE ') + label);
  }
}

if (problems.length) {
  console.log('PROBLEMS ' + problems.join(' | '));
  process.exit(1);
}
